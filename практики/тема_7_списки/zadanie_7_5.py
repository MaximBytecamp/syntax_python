# Дан список. Создать новый список из квадратов его элементов.
# ==============================================================

numbers = [1, 2, 3, 4, 5]
squares = []

for number in numbers:
    squares.append(number ** 2)

print(f"Исходный список: {numbers}")
print(f"Квадраты:        {squares}")
