# Дан список. Найти индексы всех элементов, равных x.
# ==============================================================

numbers = [3, 5, 3, 8, 3, 1]
x = int(input("Введите x: "))

for i in range(len(numbers)):
    if numbers[i] == x:
        print(i, end=" ")
print()
