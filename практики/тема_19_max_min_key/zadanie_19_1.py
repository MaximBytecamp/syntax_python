# Дан список товаров: название и цена.
# Найти самый дешевый и самый дорогой товар.
# Использовать min/max и key.
# ==============================================================

products = [
    ["хлеб", 60],
    ["молоко", 95],
    ["сыр", 320],
    ["яблоки", 140],
]

cheapest = min(products, key=lambda product: product[1])
most_expensive = max(products, key=lambda product: product[1])

print("Самый дешевый товар:", cheapest[0])
print("Самый дорогой товар:", most_expensive[0])
