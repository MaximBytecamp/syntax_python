# ==============================================================
# Задание 19.8
# Дан список слов.
# Найти слово с самым большим количеством гласных.
# ==============================================================

words = ["кот", "машина", "аэропорт"]
vowels = "аеёиоуыэюя"
result = max(words, key=lambda word: sum(1 for symbol in word if symbol in vowels))

print()
print(result)


# ==============================================================
# Задание 19.9
# Дана строка.
# Найти самый частый символ, кроме пробела.
# ==============================================================

text = "мама мыла раму"
symbols = [symbol for symbol in text if symbol != " "]
result = max(symbols, key=lambda symbol: symbols.count(symbol))

print()
print(result)


