# ==============================================================
# Задание 33.9
# Использовать super в ромбовидном наследовании.
# ==============================================================


class A:
    def show(self):
        print("A")


class B(A):
    def show(self):
        super().show()
        print("B")


class C(A):
    def show(self):
        super().show()
        print("C")


class D(B, C):
    def show(self):
        super().show()
        print("D")


obj = D()

print()
obj.show()


