# Задание 23.5
# Написать функцию, которая считает количество гласных в строке.
# ==============================================================


def count_vowels(text):
    vowels = "аеёиоуыэюя"
    count = 0

    for symbol in text:
        if symbol in vowels:
            count += 1

    return count


print()
print(count_vowels("программирование"))


