# Задание 23.9
# Написать функцию, которая возвращает список положительных чисел.
# ==============================================================


def get_positive(numbers):
    result = []

    for number in numbers:
        if number > 0:
            result.append(number)

    return result


print()
print(get_positive([-3, 5, 0, 8, -1]))


