# Написать функцию, которая принимает список чисел
# и возвращает сумму только положительных чисел.
# ==============================================================


def sum_positive(numbers):
    total = 0

    for number in numbers:
        if number > 0:
            total += number

    return total


values = [4, -2, 7, 0, -5, 10]
print(sum_positive(values))
