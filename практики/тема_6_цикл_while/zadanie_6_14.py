# ==============================================================
# Задание 6.14
# Угадать число от 1 до 100.
# После каждой попытки программа подсказывает: больше или меньше.
# ==============================================================

secret = 47
attempts = 0

guess = int(input("Угадайте число от 1 до 100: "))
attempts += 1

while guess != secret:
    if guess < secret:
        print("Загаданное число больше")
    else:
        print("Загаданное число меньше")

    guess = int(input("Попробуйте ещё раз: "))
    attempts += 1

print(f"Верно! Количество попыток: {attempts}")
