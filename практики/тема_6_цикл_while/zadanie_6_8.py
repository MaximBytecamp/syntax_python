# Последовательность чисел оканчивается нулём.
# Посчитать количество положительных чисел.
# ==============================================================

count = 0
x = int(input("Введите число: "))

while x != 0:
    if x > 0:
        count += 1
    x = int(input("Введите число: "))

print(f"Количество положительных чисел = {count}")
