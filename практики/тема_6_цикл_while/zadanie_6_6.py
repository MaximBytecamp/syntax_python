# Задание 6.6
# Дано натуральное число. Развернуть его цифры.
# Например: 1234 -> 4321.
# ==============================================================

number = int(input("Введите натуральное число: "))
reversed_number = 0

while number > 0:
    digit = number % 10
    reversed_number = reversed_number * 10 + digit
    number //= 10

print(f"Развёрнутое число = {reversed_number}")
