# Задание 6.7
# Последовательность чисел оканчивается нулём.
# Найти сумму введённых чисел, не считая 0.
# ==============================================================

total = 0
x = int(input("Введите число: "))

while x != 0:
    total += x
    x = int(input("Введите число: "))

print(f"Сумма = {total}")
