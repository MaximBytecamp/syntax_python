# Задание 6.5
# Дано натуральное число. Найти количество его цифр.
# ==============================================================

number = int(input("Введите натуральное число: "))
count = 0

if number == 0:
    count = 1
else:
    while number > 0:
        count += 1
        number //= 10

print(f"Количество цифр = {count}")
