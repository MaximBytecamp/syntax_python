# Дан список учеников: имя, оценка, количество пропусков.
# Отсортировать учеников сначала по оценке по убыванию,
# затем по количеству пропусков по возрастанию.
# ==============================================================

students = [
    ["Анна", 5, 2],
    ["Иван", 4, 0],
    ["Мария", 5, 1],
    ["Пётр", 3, 5],
]

students.sort(key=lambda student: (-student[1], student[2]))

for student in students:
    print(f"{student[0]}: оценка {student[1]}, пропуски {student[2]}")
