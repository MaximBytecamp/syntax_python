# Дана таблица температур за неделю.
# Проверить:
# а) была ли температура ниже нуля;
# б) все ли дни были не выше 30 градусов;
# в) отсортировать дни по температуре.
# ==============================================================

temperatures = [
    ["Понедельник", 12],
    ["Вторник", -2],
    ["Среда", 8],
    ["Четверг", 15],
    ["Пятница", 31],
]

has_frost = any(day[1] < 0 for day in temperatures)
all_not_hot = all(day[1] <= 30 for day in temperatures)
temperatures.sort(key=lambda day: day[1])

print(f"Была температура ниже нуля: {has_frost}")
print(f"Все дни были не выше 30 градусов: {all_not_hot}")
print("Дни по возрастанию температуры:")

for day in temperatures:
    print(f"{day[0]}: {day[1]}")
