# Дан список чисел. Найти сумму положительных элементов.
# ==============================================================

numbers = [5, -3, 0, 8, -1, 10]
total = 0

for number in numbers:
    if number > 0:
        total += number

print(f"Список: {numbers}")
print(f"Сумма положительных элементов = {total}")
