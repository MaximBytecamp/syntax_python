# ==============================================================
# Задание 18.9
# Дан список слов.
# Отсортировать слова по количеству гласных.
# ==============================================================

words = ["кот", "машина", "программа", "дом"]
vowels = "аеёиоуыэюя"
result = sorted(words, key=lambda word: sum(1 for symbol in word if symbol in vowels))

print()
print(result)


# ==============================================================
# Задание 18.10
# Дан список учеников: имя, оценка, пропуски.
# Отсортировать по оценке по убыванию, затем по пропускам по возрастанию.
