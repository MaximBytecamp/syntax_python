# Задание 18.1
# Дан список слов.
# Отсортировать слова по длине, а при равной длине — по алфавиту.
# Использовать sorted и key.
# ==============================================================

words = ["кот", "яблоко", "дом", "груша", "сон", "апельсин"]
sorted_words = sorted(words, key=lambda word: (len(word), word))

print(sorted_words)
