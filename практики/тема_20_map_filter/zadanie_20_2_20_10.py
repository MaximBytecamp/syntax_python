# ==============================================================
# Задание 20.2
# Дан список строк с числами.
# Преобразовать его в список чисел с помощью map.
# ==============================================================

values = ["1", "2", "3", "4"]
numbers = list(map(int, values))

print(numbers)


# ==============================================================
# Задание 20.3
# Дан список чисел.
# Получить список квадратов с помощью map.
# ==============================================================

numbers = [1, 2, 3, 4]
squares = list(map(lambda number: number ** 2, numbers))

print()
print(squares)


