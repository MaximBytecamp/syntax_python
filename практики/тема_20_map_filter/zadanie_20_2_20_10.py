# ==============================================================
# Задание 20.5
# Дан список чисел.
# Оставить только четные числа с помощью filter.
# ==============================================================

numbers = [1, 2, 3, 4, 5, 6]
even_numbers = list(filter(lambda number: number % 2 == 0, numbers))

print()
print(even_numbers)


# ==============================================================
# Задание 20.6
# Дан список слов.
# Оставить только слова длиной больше 4.
# ==============================================================

words = ["кот", "машина", "дом", "программа"]
long_words = list(filter(lambda word: len(word) > 4, words))

print()
print(long_words)


# ==============================================================
# Задание 20.7
# Дан список чисел.
# Оставить положительные числа и возвести их в квадрат.
# ==============================================================

numbers = [-2, 3, 0, 5, -7]
positive_numbers = filter(lambda number: number > 0, numbers)
squares = list(map(lambda number: number ** 2, positive_numbers))

print()
print(squares)


# ==============================================================
# Задание 20.8
# Дан список строк.
# Оставить только строки, которые можно превратить в число.
# ==============================================================

values = ["10", "abc", "25", "7x", "3"]
digits = list(filter(str.isdigit, values))
numbers = list(map(int, digits))

print()
print(numbers)


# ==============================================================
# Задание 20.9
# Дан список имен.
# Оставить имена, которые начинаются на букву А.
# ==============================================================

names = ["Анна", "Иван", "Артём", "Мария"]
result = list(filter(lambda name: name.startswith("А"), names))

print()
print(result)


