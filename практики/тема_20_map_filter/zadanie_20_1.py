# ==============================================================
# Задание 20.1
# Пользователь вводит числа через пробел.
# Преобразовать ввод в список чисел с помощью map.
# Оставить только положительные числа с помощью filter.
# ==============================================================

numbers = list(map(int, input("Введите числа через пробел: ").split()))
positive_numbers = list(filter(lambda number: number > 0, numbers))

print(positive_numbers)
