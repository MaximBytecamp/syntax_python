# ==============================================================
# Задание 16.9
# Создать множество пар чисел, сумма которых четная.
# Числа брать от 1 до 3.
# ==============================================================

pairs = {(i, j) for i in range(1, 4) for j in range(1, 4) if (i + j) % 2 == 0}

print()
print(pairs)


