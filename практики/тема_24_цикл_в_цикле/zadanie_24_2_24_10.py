# ==============================================================
# Задание 24.6
# Посчитать сумму всех элементов таблицы 3 на 3.
# ==============================================================

matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9],
]
total = 0

for row in matrix:
    for number in row:
        total += number

print()
print(total)


