# ==============================================================
# Задание 13.6
# Дана строка со словами.
# Найти самое длинное слово.
# ==============================================================

text = "кот программирование дом"
words = text.split()
longest = words[0]

for word in words:
    if len(word) > len(longest):
        longest = word

print()
print("Самое длинное слово:", longest)


