# Даны два списка учеников, которые посещают математику и информатику.
# Найти:
# а) кто ходит хотя бы на один предмет;
# б) кто ходит на оба предмета;
# в) кто ходит только на математику.
# ==============================================================

math_students = ["Анна", "Иван", "Мария", "Пётр"]
cs_students = ["Мария", "Олег", "Анна", "Елена"]

math_set = set(math_students)
cs_set = set(cs_students)

print(f"Хотя бы один предмет: {math_set | cs_set}")
print(f"Оба предмета: {math_set & cs_set}")
print(f"Только математика: {math_set - cs_set}")
