# Дан список списков с оценками учеников.
# Вывести среднюю оценку каждого ученика.
# ==============================================================

grades = [
    ["Анна", 5, 4, 5],
    ["Иван", 3, 4, 4],
    ["Мария", 5, 5, 5],
]

for student in grades:
    name = student[0]
    marks = student[1:]
    average = sum(marks) / len(marks)

    print(f"{name}: {average}")
