# Задание 25.9
# Дан список списков.
# Посчитать количество четных чисел.
# ==============================================================

matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9],
]
count = 0

for row in matrix:
    for number in row:
        if number % 2 == 0:
            count += 1

print()
print(count)


