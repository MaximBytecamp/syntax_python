# Задание 25.5
# Дан список списков.
# Найти максимальный элемент.
# ==============================================================

matrix = [
    [1, 12, 3],
    [4, 5, 6],
    [7, 8, 9],
]
maximum = matrix[0][0]

for row in matrix:
    for number in row:
        if number > maximum:
            maximum = number

print()
print(maximum)


