# ==============================================================
# Задание 12.8
# Даны два словаря с количеством товаров.
# Объединить их, складывая количество одинаковых товаров.
# ==============================================================

first = {"яблоки": 5, "груши": 3}
second = {"яблоки": 7, "бананы": 4}
result = first.copy()

for product, count in second.items():
    if product in result:
        result[product] += count
    else:
        result[product] = count

print()
print(result)


# ==============================================================
# Задание 12.9
# Дан словарь с городами и населением.
# Найти город с самым большим населением.
# ==============================================================

cities = {"Москва": 13100000, "Казань": 1320000, "Сочи": 450000}
largest_city = ""
largest_population = 0

for city, population in cities.items():
    if population > largest_population:
        largest_city = city
        largest_population = population

print()
print("Самый большой город:", largest_city)


# ==============================================================
# Задание 12.10
# Дан список слов.
# Сгруппировать слова по первой букве в словарь.
# ==============================================================

words = ["кот", "кит", "дом", "дуб", "арбуз"]
groups = {}

for word in words:
    first_letter = word[0]

    if first_letter not in groups:
        groups[first_letter] = []

    groups[first_letter].append(word)

print()
print(groups)
