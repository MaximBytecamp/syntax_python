# Дан список слов.
# Посчитать, сколько раз встречается каждое слово.
# ==============================================================

words = ["кот", "пёс", "кот", "рыба", "пёс", "кот"]
counts = {}

for word in words:
    if word in counts:
        counts[word] += 1
    else:
        counts[word] = 1

print(counts)
