print()
print(numbers)


# ==============================================================
# Задание 15.7
# Дан список чисел.
# Заменить отрицательные числа на 0.
# ==============================================================

numbers = [5, -2, 8, -7, 0]
result = [number if number >= 0 else 0 for number in numbers]

print()
print(result)


# ==============================================================
# Задание 15.8
# Дан список списков.
# Создать один общий список всех чисел.
# ==============================================================

matrix = [[1, 2], [3, 4], [5, 6]]
