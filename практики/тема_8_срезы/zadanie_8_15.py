# Задание 8.15
# Дан список чисел. Разделить его на две части:
# первая половина и вторая половина.
# Если элементов нечётное количество, средний элемент попадает во вторую часть.
# ==============================================================

numbers = [1, 2, 3, 4, 5, 6, 7]
middle = len(numbers) // 2

first_part = numbers[:middle]
second_part = numbers[middle:]

print(f"Список: {numbers}")
print(f"Первая часть: {first_part}")
print(f"Вторая часть: {second_part}")
