# Дан список товаров: название и цена.
# С помощью sorted и lambda отсортировать товары по цене.
# ==============================================================

products = [
    ["хлеб", 60],
    ["молоко", 95],
    ["яблоки", 140],
    ["чай", 220],
]

sorted_products = sorted(products, key=lambda product: product[1])

print("Товары по возрастанию цены:")
for product in sorted_products:
    print(f"{product[0]} — {product[1]} руб.")
