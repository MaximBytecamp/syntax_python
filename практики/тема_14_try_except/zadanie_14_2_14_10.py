# ==============================================================
# Задание 14.9
# Использовать блок finally.
# Он выполняется в любом случае.
# ==============================================================

text = "python"

print()
try:
    number = int(text)
    print(number)
except ValueError:
    print("Не получилось преобразовать")
finally:
    print("Проверка завершена")


