# ==============================================================
# Задание 17.7
# Дан словарь температур в градусах Цельсия.
# Создать словарь температур в градусах Фаренгейта.
# ==============================================================

celsius = {"утро": 10, "день": 18, "вечер": 12}
fahrenheit = {time: temperature * 9 / 5 + 32 for time, temperature in celsius.items()}

print()
