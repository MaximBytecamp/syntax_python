# ==============================================================
# Задание 17.10
# Дан список списков с оценками.
# Создать словарь: имя — средняя оценка.
# ==============================================================

students = [["Анна", 5, 4, 5], ["Иван", 3, 4, 4], ["Мария", 5, 5, 5]]
