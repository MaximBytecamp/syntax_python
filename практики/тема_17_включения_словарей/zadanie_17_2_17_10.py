# ==============================================================
# Задание 17.8
# Дан список слов.
# Создать словарь: слово — количество гласных в слове.
# ==============================================================

words = ["кот", "машина", "программа"]
vowels = "аеёиоуыэюя"
counts = {word: sum(1 for symbol in word if symbol in vowels) for word in words}

print()
print(counts)


