from math import sqrt
from random import randint


# ==============================================================
# Задание 22.1
# Сгенерировать случайное число от 1 до 100.
# Найти квадратный корень из этого числа.
# Использовать библиотеки math и random.
# ==============================================================

number = randint(1, 100)
root = sqrt(number)

print("Число:", number)
print("Квадратный корень:", root)
